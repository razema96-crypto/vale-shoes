import type { PublicSettings } from "./types";

const nf = new Intl.NumberFormat("en-US", { maximumFractionDigits: 2 });

/** "1,250 ر.س" — digits kept Western & isolated so they never flip inside RTL text. */
export function formatPrice(n: number, s?: Pick<PublicSettings, "currencySymbol"> | null) {
  return `${nf.format(n)} ${s?.currencySymbol ?? ""}`.trim();
}

/** Prices are shown only when the owner turns them on in settings. */
export function pricesOn(s?: { showPrices?: boolean } | null) {
  return !!s?.showPrices;
}

