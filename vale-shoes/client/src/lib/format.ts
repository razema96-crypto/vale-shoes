export function imageFor(p: { images: { url: string; color?: string }[] }, color?: string) {
  if (color) {
    const m = p.images.find((i) => i.color === color);
    if (m) return m.url;
  }
  return p.images[0]?.url;
}

/** Smaller copy of a product photo for grids and lists (generated by the server on first request). */
export function thumb(url: string | undefined, w: 400 | 800 = 400) {
  if (!url || import.meta.env.VITE_PREVIEW === "1") return url;
  const m = url.match(/^\/(uploads|demo-images)\/([\w.\-]+\.webp)$/);
  return m ? `/thumb/${w}/${m[1]}/${m[2]}` : url;
}

/** srcset for a card image: phones get 400px, larger screens 800px. */
export function thumbSet(url: string | undefined) {
  const a = thumb(url, 400), b = thumb(url, 800);
  return a && b && a !== url ? `${a} 400w, ${b} 800w` : undefined;
}

export function prefersReducedMotion() {
  return typeof window !== "undefined" && window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
}
